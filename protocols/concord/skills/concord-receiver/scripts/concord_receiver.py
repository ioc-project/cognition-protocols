class FileStore:
    """A state kept in one JSON file. A save writes a temporary file next to it and renames it over the old one, so a reader
    (or a crash) never sees half a state. The rename gives the file a new identity: serialise writers with a lock on a
    separate file, not on this one."""

    def __init__(self, path, indent=2):
        self.path = Path(path)
        self.indent = indent

    def exists(self):
        return self.path.exists()

    def load(self):
        if not self.path.exists():
            raise MissingState(f"no state file at {self.path}")
        try:
            return json.loads(self.path.read_text(encoding="utf-8"))
        except ValueError as exc:
            raise StateError(f"state file {self.path} is not valid JSON ({exc})")

    def save(self, state):
        text = json.dumps(state, indent=self.indent) + "\n"          # first: a state that is not JSON leaves the file alone
        tmp = self.path.with_name(f".{self.path.name}.{os.getpid()}.tmp")
        try:
            tmp.write_text(text, encoding="utf-8")
            os.replace(tmp, self.path)
        finally:
            tmp.unlink(missing_ok=True)

# --- ioc_concord.state ---

PARTICIPANT, INITIATOR = "participant", "initiator"
RUN_ACTIVE, RUN_ENDED, RUN_ABORTED = "active", "ended", "aborted"


def new_agent_state(me):
    if not is_agent_id(me):
        raise StateError(f"an agent id is 1 to 64 letters, digits, _ or -, not {me!r}")
    return {"me": me, "runs": {}, "active": None}


# What a saved run holds (see the top of this module): the keys, and which of them are lists and which are dicts.
RUN_KEYS = ("role", "run_id", "initiator", "participants", "params", "context", "x_reject", "x_ideal", "schema", "engine", "sent",
            "sent_by_uuid", "received", "uuids", "outcome", "reported", "mismatches", "timers", "held", "expected", "unrated", "abort",
            "cancel_sent", "disputed", "status")
_RUN_LISTS = ("participants", "expected", "unrated")
_RUN_DICTS = ("params", "schema", "engine", "sent", "sent_by_uuid", "received", "uuids", "mismatches", "timers", "held")
_ENGINE_KEYS = tuple(new_engine_state(["a", "b"], DEFAULT_PARAMS))


def check_agent_state(state, me):
    """`state` itself, if it is the saved state of the agent `me`: the shape that the agent relies on, not every value in it. Raises
    StateError, with the reason, otherwise, so that a state that is not one is never taken for an empty one or fails later with a
    KeyError. What `new_agent_state` and `new_run` make passes."""
    def bad(why):
        raise StateError(f"the saved state is not the state of an agent: {why}")

    if not isinstance(state, dict):
        bad("it is not a JSON object")
    if state.get("me") != me:
        raise StateError(f"the saved state belongs to {state.get('me')!r}, not to {me!r}")
    runs = state.get("runs")
    if not isinstance(runs, dict):
        bad('"runs" is not an object')
    if state.get("active") is not None and state["active"] not in runs:
        bad('"active" names a run that is not in "runs"')
    for run_id, run in runs.items():
        if not is_uuid(run_id):
            bad(f"{run_id!r} is not a run id")
        if not isinstance(run, dict):
            bad(f"the run {run_id} is not an object")
        missing = [k for k in RUN_KEYS if k not in run]
        if missing:
            bad(f"the run {run_id} lacks {', '.join(missing)}")
        if run["run_id"] != run_id:
            bad(f"the run {run_id} says it is {run['run_id']!r}")
        if run["role"] not in (PARTICIPANT, INITIATOR) or run["status"] not in (RUN_ACTIVE, RUN_ENDED, RUN_ABORTED):
            bad(f"the run {run_id} has a role or a status that is not one")
        for k in _RUN_LISTS:
            if not isinstance(run[k], list):
                bad(f'"{k}" of the run {run_id} is not a list')
        for k in _RUN_DICTS:
            if not isinstance(run[k], dict):
                bad(f'"{k}" of the run {run_id} is not an object')
        if not all(is_agent_id(a) for a in run["participants"]) or not is_agent_id(run["initiator"]):
            bad(f"the run {run_id} names an agent that has no valid id")
        if set(run["params"]) != set(DEFAULT_PARAMS) or any(k not in run["engine"] for k in _ENGINE_KEYS):
            bad(f"the run {run_id} holds no parameters or no engine state")
    return state


def item_key(kind, author, item=None):
    """The key of an item: `init-reply|cost`, `score|cost|seed-security`, `result|cost`."""
    return "|".join(p for p in (kind, author, item) if p)


# How many accepted uuids a run keeps. The spec keeps them all, but a participant can send as many messages as it likes, each with a new
# uuid, so this library forgets the oldest past this number (far above what an honest run sends). A copy of a message that is that old
# and arrives again is read once more, which the rules of the protocol make harmless.
MAX_UUIDS = 4096


def keep_uuid(run, uid):
    """Remember that the transmission `uid` has been accepted, and forget the oldest ones past MAX_UUIDS."""
    uuids = run["uuids"]
    uuids[uid] = True
    while len(uuids) > MAX_UUIDS:
        del uuids[next(iter(uuids))]


def keep_sent(run, key, text):
    """Keep `text`, the original that this agent sent for the item `key`, to send it again word for word."""
    run["sent"][key] = text
    run["sent_by_uuid"][peek(text)["attrs"]["uuid"]] = text


def new_run(me, init, doc):
    """The run that the parsed init `init` (see wire.parse_message) opens for `me`, with the init text `doc`: as received, or as
    sent when `me` is the initiator. An initiator that is not a participant has the role INITIATOR: it negotiates nothing, and
    only watches the init replies and the result."""
    params = dict(init["params"])
    mine = init["from"] == me
    run = {"role": PARTICIPANT if me in init["participants"] else INITIATOR, "run_id": init["run_id"],
            "initiator": init["from"], "participants": list(init["participants"]), "params": params, "context": init["context"],
            "x_reject": init["x_reject"], "x_ideal": init["x_ideal"], "schema": init["schema"],
            "engine": new_engine_state(init["participants"], params),
            "sent": {}, "sent_by_uuid": {}, "received": {} if mine else {item_key("init", init["from"]): doc},
            "uuids": {init["uuid"]: True}, "outcome": None, "reported": None,
            "mismatches": {"sent": 0, "last": None, "received": []},
            "timers": {}, "held": {}, "expected": [], "unrated": [], "abort": None, "cancel_sent": False, "disputed": False,
            "status": RUN_ACTIVE}
    if mine:
        keep_sent(run, item_key("init", me), doc)
    return run


def members(run):
    """The agents that may send a message of the run: its participants and its initiator."""
    return set(run["participants"]) | {run["initiator"]}


def active_run(state):
    """The run that is active for the agent, or None."""
    run = state["runs"].get(state["active"]) if state["active"] else None
    return run if run is not None and run["status"] == RUN_ACTIVE else None

# --- ioc_concord.liveness ---

def lacking_by(run):
    """{agent: [candidate ids it has not rated yet], in pool order}. Before every init reply is in nothing is owed, so it is empty."""
    st, out = run["engine"], {}
    if len(st["anchors"]) < len(st["agents"]):
        return out
    for agent, cid in lacking(st):
        out.setdefault(agent, []).append(cid)
    return out


def owed_batches(run, me, ev):
    """{timer key: {author, what, candidate}}: the batches of messages that `me` is owed now, given the evaluation `ev` of the engine
    over the run. An agent is never owed its own messages. An initiator that does not negotiate is owed the init replies, and no timer
    runs for the result."""
    out = {}
    if run["status"] != RUN_ACTIVE:
        return out
    st, reporter = run["engine"], run["participants"][0]

    def owe(key, author, what, candidate=None):
        out[key] = {"author": author, "what": what, "candidate": candidate}

    for a in run["participants"]:
        if a != me and a not in st["anchors"]:
            owe(f"init-reply|{a}", a, "init-reply")
    if run["role"] == INITIATOR:
        return out
    for author, candidates in lacking_by(run).items():
        for cid in candidates:
            if author != me:
                batch = "seeds" if parse_candidate_id(cid)[0] == 0 else cid
                out.setdefault(f"score|{author}|{batch}", {"author": author, "what": "score", "candidate": cid})
    have = {c["id"] for c in st["pool"]}
    for cid in run["expected"]:
        rnd, author = parse_candidate_id(cid)
        if cid not in have and author != me:
            if rnd == 0:
                owe(f"init-reply|{author}", author, "init-reply")
            else:
                owe(f"repair|{author}|{rnd}", author, "repair", cid)
    if ev["state"] == "repair" and ev["bottleneck"] != me:
        owe(f"repair|{ev['bottleneck']}|{ev['round']}", ev["bottleneck"], "repair", f"r{ev['round']}-{ev['bottleneck']}")
    if run["outcome"] not in (None, ABORTED) and me != reporter and run["reported"] is None:
        owe(f"result|{reporter}", reporter, "result")
    return out


def sync_timers(run, me, now, ev):
    """Start the timer of every batch that has become owed, and drop the timer of every batch that is complete. When the message that was
    first lacking in a batch has arrived and the next is still owed, the wait starts again."""
    owed, timers = owed_batches(run, me, ev), run["timers"]
    for key in [k for k in timers if k not in owed]:
        del timers[key]
    for key, o in owed.items():
        t = timers.get(key)
        if t is None or t["candidate"] != o["candidate"]:
            deadline = now + run["params"]["timeout"]
            t = timers[key] = {"requests": 0, "asked": False, "deadline": deadline, "candidate": o["candidate"]}
        t.update(o)


def expired_keys(run, now):
    """The keys of the timers of `run` that have expired at `now`, the earliest first."""
    return [key for _, key in sorted((t["deadline"], key) for key, t in run["timers"].items()
                                     if t["deadline"] <= now)]


def earliest_deadline(runs):
    """The earliest deadline of a timer of an active run among `runs`, or None."""
    due = [t["deadline"] for run in runs if run["status"] == RUN_ACTIVE for t in run["timers"].values()]
    return min(due) if due else None

# --- ioc_concord.tasks ---

def to_rate(run, me):
    """The candidates of the others that `me` has not rated, once every init reply is in."""
    return lacking_by(run).get(me, [])


def tasks_of(run, me):
    """The tasks `me` owes in `run` (none when `run` is None, or `me` does not negotiate in it), as dicts with a `kind`: `init-reply`, `score` or `repair`. See
    `Agent.due` for what each holds."""
    if run is None or run["role"] != PARTICIPANT:
        return []
    st = run["engine"]
    if item_key("init-reply", me) not in run["sent"]:
        return [{"kind": "init-reply", "run_id": run["run_id"], "initiator": run["initiator"], "context": run["context"],
                 "x_reject": run["x_reject"], "x_ideal": run["x_ideal"], "schema": run["schema"]}]
    owed = to_rate(run, me)
    if not owed:
        return _repair_task(run, me)
    by_id = {c["id"]: c for c in st["pool"]}
    return [{"kind": "score", "run_id": run["run_id"], "candidates": [
        {"id": cid, "from": by_id[cid]["proposer"], "candidate": by_id[cid]["candidate"],
         "rationale": by_id[cid]["rationale"], "reasoning": st["reasoning"][by_id[cid]["proposer"]].get(cid, "")}
        for cid in owed]}]


def _repair_task(run, me):
    ev = evaluate(run["engine"])
    if ev["state"] != "repair" or ev["bottleneck"] != me or item_key("repair", me, f"r{ev['round']}-{me}") in run["sent"]:
        return []
    st, x = run["engine"], ev["x_star"]
    inc = next(c for c in st["pool"] if c["id"] == x)
    text = lambda d: {a: format_number(v) for a, v in d.items()}
    return [{"kind": "repair", "run_id": run["run_id"], "round": ev["round"],
             "incumbent": {"id": x, "candidate": inc["candidate"], "rationale": inc["rationale"]},
             "threshold": format_number(st["params"]["satisfaction_threshold"]), "floor": format_number(ev["floor"]),
             "scores": text(ev["scores"]), "shortfall": text(ev["shortfall"]),
             "reasoning": {a: st["reasoning"][a].get(x, "") for a in st["agents"]},
             "repairs_left": st["params"]["B"] - ev["t"]}]

