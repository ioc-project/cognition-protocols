PROG = "concord_receiver.py"
STOP_AFTER = 3          # the same refusal this many times in a row: stop (spec, Appendix A.7)
STOP_AFTER_ANY = 6      # refusals of one task in a row, whatever their reasons: stop too (a model that changes its bad answer each time)

# What an answer holds, for each kind of task: (field, kind of value, what it is). The names are those of the library. The format text
# that a task carries, and the checks of an answer before the library's own, come from this table.
RAW_SCALE = "a number from 0 to 100 on YOUR raw scale (never a normalised 0-1 score)"
FIELDS = {
    "init-reply": [
        ("raw_reject", "number", "how satisfied your role would be if x_reject happened: 0 to 100, usually low"),
        ("raw_ideal", "number", "how satisfied your role would be if x_ideal happened: 0 to 100, usually high, above raw_reject"),
        ("candidate", "text", "the one option that suits your role best, in the format the task describes"),
        ("rationale", "text", "why this option, with the facts you hold that bear on it: the others read it"),
        ("raw", "number", f"your own score for this option, {RAW_SCALE}. It goes in this field, not only in the reasoning"),
        ("reasoning", "text", "why that score, with the facts behind it"),
    ],
    "score": [("scores", "list", "one entry for each candidate the task lists, and no other")],
    "repair": [
        ("candidate", "text", "a better option than the incumbent, in the format the task describes"),
        ("rationale", "text", "why this option, with the facts that bear on it"),
        ("raw", "number", f"your own score for this option, {RAW_SCALE}. It goes in this field, not only in the reasoning"),
        ("reasoning", "text", "why that score"),
    ],
}
ENTRY = [
    ("id", "text", "the id of the candidate, exactly as in the task"),
    ("raw", "number", f"your rating of it, {RAW_SCALE}"),
    ("reasoning", "text", "why that rating, with the facts behind it"),
]
KINDS = {"number": "a number", "text": "text", "list": "a list"}


def answer_format(task, command):
    """The text that tells the model what to pass to `answer` for `task` (printed after the task)."""
    rows = FIELDS[task["kind"]]
    out = [f"ANSWER FORMAT: write one JSON object with exactly these fields, and pass it on standard input to `{command}`. Nothing else:"]
    out += [f"  {name} ({KINDS[kind]}): {what}" for name, kind, what in rows]
    if task["kind"] == "score":
        out.append("  each entry of scores is an object:")
        out += [f"    {name} ({KINDS[kind]}): {what}" for name, kind, what in ENTRY]
    shape = {"number": 70, "text": "...", "list": [{n: (70 if k == "number" else "...") for n, k, _ in ENTRY}]}
    out.append("  for example: " + json.dumps({name: shape[kind] for name, kind, _ in rows}))
    return "\n".join(out)


def _fits(kind, value):
    if kind == "number":
        return isinstance(value, (int, float, str)) and not isinstance(value, bool)
    return isinstance(value, str) if kind == "text" else isinstance(value, list)


def wrong_shapes(rows, obj, where=""):
    """The fields of `obj` that are there but of the wrong kind of value, as a sentence (empty when all are right)."""
    return " ".join(wrong_shape(where + name, KINDS[kind], obj[name]) for name, kind, _ in rows
                    if obj.get(name) is not None and not _fits(kind, obj[name]))


def missing_fields(kind, answer):
    """The fields the answer lacks, as a sentence that shows what was sent next to what is expected (empty when none is lacking)."""
    rows, top, nested = FIELDS[kind], [], []
    for name, _, what in rows:
        if answer.get(name) in (None, ""):
            top.append(f"`{name}` ({what})")
    if kind == "score" and isinstance(answer.get("scores"), list):
        for n, entry in enumerate(answer["scores"], 1):
            have = ", ".join(entry) if isinstance(entry, dict) else "nothing"
            suffix = f" [the entry has: {have}; an entry takes: {', '.join(name for name, _, _ in ENTRY)}]"
            nested += [f"entry {n} of `scores`: `{name}` ({what}){suffix}" for name, _, what in ENTRY
                       if isinstance(entry, dict) and entry.get(name) in (None, "")]
    if nested:
        return lacks(nested + top)
    return lacks(top, sent=list(answer), takes=[name for name, _, _ in rows]) if top else ""


def problems(task, session, text):
    """(the answer as a dict, None), or (None, what is wrong with `text`): its shape, what it lacks, and the checks beyond the
    specification, in that order. The library's own checks come when it is submitted."""
    try:
        answer = json.loads(text)
    except ValueError as exc:
        return None, f"the answer is not valid JSON ({exc}): pass one JSON object"
    if not isinstance(answer, dict):
        return None, wrong_shape("answer", "an object", answer)
    kind = task["kind"]
    shape = wrong_shapes(FIELDS[kind], answer)
    if kind == "score" and isinstance(answer.get("scores"), list):
        entries = [wrong_shape(f"scores` entry `{n}", "an object with " + ", ".join(name for name, _, _ in ENTRY), e)
                   for n, e in enumerate(answer["scores"], 1) if not isinstance(e, dict)]
        shape = " ".join([shape] + entries + [wrong_shapes(ENTRY, e, f"scores` entry `{n}` field `")
                                              for n, e in enumerate(answer["scores"], 1) if isinstance(e, dict)]).strip()
    if shape:
        return None, shape
    lack = missing_fields(kind, answer)
    if lack:
        return None, lack
    view = run_view(session.agent.state["runs"][task["run_id"]], session.me)
    anchors = {k: float(v) for k, v in view["anchors"].items()} if view["anchors"] else None
    found = check_answer(kind, answer, anchors)
    return (None, " ".join(found)) if found else (answer, None)


def task_key(task):
    """What identifies a task: the same task is asked again until it is answered, and a refusal of it is counted with the earlier ones."""
    return [task["run_id"], task["kind"], task.get("round"), sorted(c["id"] for c in task.get("candidates", []))]


def refuse(session, task, error):
    """The output for an answer that was refused: what is wrong and what to do (guidance), and, when it goes on, the stop that the
    specification asks for (A.7: limit the retries). Two counts, both of consecutive refusals of the same task: the same refusal again
    and again (the stop is at STOP_AFTER, and guidance tells the model to change its answer from the second), and refusals for any
    reason (the stop is at STOP_AFTER_ANY): a model that changes its bad answer each time never repeats a refusal. A refusal that says
    the answer is already given (`task` is None then) is not counted."""
    same = tries = 1
    if not settled(error):
        key, why = task_key(task), str(error)
        last = session.side["refusal"] or {}
        if last.get("task") == key:
            tries = last["tries"] + 1
            same = last["same"] + 1 if last["text"] == why else 1
        session.side["refusal"] = {"task": key, "tries": tries, "text": why, "same": same}
    said, _, hint = refusal(error, same).partition("\nNEXT: ")
    out = Out("ERROR")
    out.add("REFUSED", said)
    out.next = hint
    if same >= STOP_AFTER or tries >= STOP_AFTER_ANY:
        how = f"The same refusal came {same} times in a row" if same >= STOP_AFTER else f"This task has been refused {tries} times in a row"
        out.next = (f"Stop. {how}, so the answer cannot be obtained. Do not try again and do not work around it: report that you could not "
                    "answer this task, and why (quote the refusal above). Silence ends the run for everybody after a while, which is the "
                    "right outcome here.")
    return out


def run_answer(factory, args, text):
    """Answer the task that is due: check the answer, submit it to the library, and print what follows."""
    with factory() as s:
        agent, tasks = s.agent, s.agent.due()
        if not tasks:
            return refuse(s, None, StateError("nothing is due from you now: that is answered already, or not yours to answer"))
        task = tasks[0]
        answer, wrong = problems(task, s, text)
        if wrong:
            return refuse(s, task, wrong)
        before, run_id = s.before(), task["run_id"]
        try:
            if task["kind"] == "init-reply":
                step = agent.submit_init_reply(run_id, answer["raw_reject"], answer["raw_ideal"], answer["candidate"],
                                               answer["rationale"], answer["raw"], answer["reasoning"])
            elif task["kind"] == "score":
                step = agent.submit_score(run_id, [(e["id"], e["raw"], e["reasoning"]) for e in answer["scores"]])
            else:
                step = agent.submit_repair(run_id, answer["candidate"], answer["rationale"], answer["raw"], answer["reasoning"])
        except ConcordError as exc:
            return refuse(s, task, exc)
        except Exception as exc:                          # a bug, or an answer of a shape nobody foresaw: never a bare traceback
            traceback.print_exc(file=sys.stderr)
            return refuse(s, task, UNEXPECTED.format(kind=type(exc).__name__, detail=exc))
        s.side["refusal"] = None
        return s.compose(step, before)


def run_task(factory, args, text):
    """What is due now, as after any call: the task if there is one, and the timer. It changes nothing."""
    with factory() as s:
        s.need_run()
        return s.compose(Step(s.agent.clock()), s.before())


def run_status(factory, args, text):
    """Where the run stands, for a person who debugs: the view of the engine, and the timers."""
    with factory() as s:
        st = s.need_run()
        out = Out("WAIT" if st["status"] == "active" else "DONE")
        scores = {a: format_number(v) for a, v in st["scores"].items()}
        lines = [f"run_id: {st['run_id']}", f"role: {st['role']}", f"status: {st['status']}", f"outcome: {st['outcome']}",
                 f"state: {st['state']} (round {st['round']}, reporter {st['reporter']})", f"incumbent: {st['x_star']}",
                 f"scores: {scores}", f"bottleneck: {st['bottleneck']}", f"anchors in: {', '.join(st['anchors_in']) or 'none'}",
                 f"lacking: {st['lacking']}"]
        lines += [f"timer {key}: {wake_text(due, s.agent.clock())}" for key, due in st["timers"].items()]
        out.add("STATE", "\n".join(lines))
        out.next = f"This is a view for debugging: it changes nothing. To go on, see the NEXT line of your last call, or run `{s.command('report')}`."
        return out


